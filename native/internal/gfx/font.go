// glyphRows holds each glyph decoded to a 7-row bitmask (bit 4 = leftmost column).
var glyphRows = func() map[rune][7]uint8 {
	out := make(map[rune][7]uint8, len(glyphs))
	for r, s := range glyphs {
		var rows [7]uint8
		for i, row := range strings.Fields(s) {
			for c, ch := range row {
				if ch == '#' {
					rows[i] |= 1 << (4 - c)
				}
			}
		}
		out[r] = rows
	}
	return out
}()

// GlyphWidth is the advance in font pixels of one character (5 columns + 1 spacing).
const GlyphWidth = 6

// TextWidth returns the width in font pixels of s at scale 1.
func TextWidth(s string) int { return len([]rune(s)) * GlyphWidth }
